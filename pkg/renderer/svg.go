package renderer

import (
	"bytes"
	"fmt"
	"html"
	"strings"

	"github.com/alainairom/github-contribution-city/pkg/city"
)

// SVGRenderer renders CityScene into standalone SVG images
type SVGRenderer struct{}

// NewSVGRenderer creates a new SVGRenderer
func NewSVGRenderer() *SVGRenderer {
	return &SVGRenderer{}
}

// RenderSkyline renders the classic 2D skyline ASCII/block-style SVG
func (r *SVGRenderer) RenderSkyline(scene *city.CityScene, themeName string) string {
	theme := GetTheme(themeName)

	cellWidth := 14.0
	cellHeight := 18.0
	headerHeight := 80.0
	footerHeight := 45.0
	paddingX := 40.0

	svgWidth := float64(scene.GridWidth)*cellWidth + paddingX*2
	svgHeight := float64(scene.GridHeight)*cellHeight + headerHeight + footerHeight

	var buf bytes.Buffer
	buf.WriteString(fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %.1f %.1f" width="100%%" height="100%%" style="background-color: %s; font-family: ui-monospace, 'Cascadia Code', 'Source Code Pro', Menlo, Consolas, monospace; border-radius: 8px;">`,
		svgWidth, svgHeight, theme.Background))

	// CSS Styles
	buf.WriteString(fmt.Sprintf(`
<style>
  .title { font-size: 18px; font-weight: bold; fill: %s; }
  .subtitle { font-size: 12px; fill: %s; }
  .stat-label { font-size: 11px; fill: %s; }
  .stat-val { font-weight: bold; fill: %s; }
  .month-label { font-size: 11px; fill: %s; font-weight: 500; }
  .cell-text { font-size: 13px; text-anchor: middle; dominant-baseline: central; }
  .building-cell { transition: opacity 0.2s ease; }
  .building-cell:hover { opacity: 0.8; cursor: pointer; }
</style>
`, theme.TextPrimary, theme.TextSecondary, theme.TextMuted, theme.TextPrimary, theme.TextSecondary))

	// Header Background Gradient or Accent
	buf.WriteString(fmt.Sprintf(`<rect width="%.1f" height="%.1f" fill="%s" rx="8" />`, svgWidth, svgHeight, theme.Background))

	// Header Text
	buf.WriteString(fmt.Sprintf(`<text x="%.1f" y="32" class="title">🌆 %s's Contribution City</text>`, paddingX, html.EscapeString(scene.Username)))
	subtitle := fmt.Sprintf("%d total contributions across %d weeks • Busiest week: %d contributions",
		scene.TotalContributions, len(scene.Buildings3D), scene.MaxWeeklyTotal)
	buf.WriteString(fmt.Sprintf(`<text x="%.1f" y="52" class="subtitle">%s</text>`, paddingX, html.EscapeString(subtitle)))

	// Grid Origin
	originY := headerHeight

	// Render Cells
	for rowIdx, row := range scene.Grid {
		yPos := originY + float64(rowIdx)*cellHeight + cellHeight/2.0
		for colIdx, cell := range row {
			xPos := paddingX + float64(colIdx)*cellWidth + cellWidth/2.0
			rectX := paddingX + float64(colIdx)*cellWidth
			rectY := originY + float64(rowIdx)*cellHeight

			switch cell.Kind {
			case city.CellWindow:
				winColor := theme.WindowLevels[cell.Level]
				// Draw window rect with tooltip
				buf.WriteString(fmt.Sprintf(`<rect class="building-cell" x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="%s" rx="2" stroke="%s" stroke-width="0.5">`,
					rectX+1, rectY+1, cellWidth-2, cellHeight-2, winColor, theme.BuildingEdge))
				tooltip := fmt.Sprintf("Date: %s | %d contributions", cell.Date, cell.Count)
				if cell.Date == "" {
					tooltip = fmt.Sprintf("Week %d", cell.WeekIndex+1)
				}
				buf.WriteString(fmt.Sprintf(`<title>%s</title></rect>`, html.EscapeString(tooltip)))

			case city.CellRoof:
				buf.WriteString(fmt.Sprintf(`<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="%s" rx="1" />`,
					rectX+1, rectY+1, cellWidth-2, cellHeight-2, theme.BuildingRoof))
				buf.WriteString(fmt.Sprintf(`<text x="%.1f" y="%.1f" class="cell-text" fill="%s">%c</text>`,
					xPos, yPos, theme.TextSecondary, cell.Char))

			case city.CellAntenna:
				buf.WriteString(fmt.Sprintf(`<text x="%.1f" y="%.1f" class="cell-text" fill="%s" font-weight="bold">%c</text>`,
					xPos, yPos, theme.Antenna, cell.Char))

			case city.CellStreet:
				buf.WriteString(fmt.Sprintf(`<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="%s" />`,
					rectX, rectY, cellWidth, cellHeight, theme.Street))
				buf.WriteString(fmt.Sprintf(`<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" stroke-width="2" stroke-dasharray="4,2" />`,
					rectX, yPos, rectX+cellWidth, yPos, theme.StreetLine))
			}
		}
	}

	// Month Labels below street
	monthY := originY + float64(len(scene.Grid))*cellHeight + 15
	for _, ml := range scene.MonthLabels {
		xPos := paddingX + float64(ml.Column)*cellWidth
		buf.WriteString(fmt.Sprintf(`<text x="%.1f" y="%.1f" class="month-label">%s</text>`, xPos, monthY, ml.MonthName))
	}

	// Footer Stats
	footerY := svgHeight - 12
	buf.WriteString(fmt.Sprintf(`<text x="%.1f" y="%.1f" class="stat-label">Generated by <tspan class="stat-val">GitHub Contribution City (Go)</tspan> • Inspired by Quarkus Contribution City</text>`,
		paddingX, footerY))

	buf.WriteString("\n</svg>")
	return buf.String()
}

// RenderIsometric3D renders a true 3D Isometric SVG city with prisms and lighting
func (r *SVGRenderer) RenderIsometric3D(scene *city.CityScene, themeName string) string {
	theme := GetTheme(themeName)

	numBuildings := len(scene.Buildings3D)
	if numBuildings == 0 {
		return r.RenderSkyline(scene, themeName)
	}

	// Isometric projection parameters
	// Iso transform:
	// screenX = (gridX - gridZ) * tileW + centerX
	// screenY = (gridX + gridZ) * tileH - height * scaleH + centerY
	tileW := 22.0
	tileH := 11.0
	blockWidth := 18.0
	heightScale := 12.0
	footerHeight := 45.0

	// Calculate bounds
	svgWidth := float64(numBuildings)*tileW*1.8 + 200.0
	if svgWidth < 800 {
		svgWidth = 800
	}
	svgHeight := 480.0 + float64(scene.MaxWeeklyTotal)*heightScale*0.5
	if svgHeight > 900 {
		svgHeight = 900
	}

	var buf bytes.Buffer
	buf.WriteString(fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %.1f %.1f" width="100%%" height="100%%" style="background-color: %s; font-family: ui-monospace, 'Cascadia Code', Menlo, monospace; border-radius: 8px;">`,
		svgWidth, svgHeight, theme.Background))

	buf.WriteString(fmt.Sprintf(`
<style>
  .title { font-size: 18px; font-weight: bold; fill: %s; }
  .subtitle { font-size: 12px; fill: %s; }
  .iso-building { transition: transform 0.2s, filter 0.2s; }
  .iso-building:hover { filter: brightness(1.25); cursor: pointer; }
  .antenna { stroke: %s; stroke-width: 2; }
  .beacon { fill: %s; animation: pulse 1.5s infinite; }
  .stat-label { font-size: 11px; fill: %s; }
</style>
`, theme.TextPrimary, theme.TextSecondary, theme.Antenna, theme.Antenna, theme.TextMuted))

	// Background
	buf.WriteString(fmt.Sprintf(`<rect width="%.1f" height="%.1f" fill="%s" rx="8" />`, svgWidth, svgHeight, theme.Background))

	// Header
	buf.WriteString(fmt.Sprintf(`<text x="40" y="32" class="title">🏙️ %s's 3D Contribution City</text>`, html.EscapeString(scene.Username)))
	subtitle := fmt.Sprintf("%d total contributions • %d weeks • %s theme • 3D Isometric Projection",
		scene.TotalContributions, numBuildings, strings.ToUpper(theme.Name))
	buf.WriteString(fmt.Sprintf(`<text x="40" y="52" class="subtitle">%s</text>`, html.EscapeString(subtitle)))

	// Isometric City Base Platform
	baseY := svgHeight - footerHeight - 80.0
	startX := 80.0

	// Draw Street Ground line
	buf.WriteString(fmt.Sprintf(`<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" stroke-width="4" stroke-linecap="round" />`,
		startX-20, baseY+20, svgWidth-60, baseY+20, theme.Street))

	// Render Isometric Buildings from left to right
	for i, b := range scene.Buildings3D {
		xBase := startX + float64(i)*tileW*1.6
		yBase := baseY + (b.GridZ * tileH)
		bldgH := float64(b.Floors) * heightScale

		topY := yBase - bldgH

		// Isometric building coordinates
		// Top face (Rhombus):
		// P1: (xBase, topY)
		// P2: (xBase + blockWidth, topY + tileH)
		// P3: (xBase, topY + tileH * 2)
		// P4: (xBase - blockWidth, topY + tileH)
		pTop := fmt.Sprintf("%.1f,%.1f %.1f,%.1f %.1f,%.1f %.1f,%.1f",
			xBase, topY,
			xBase+blockWidth, topY+tileH,
			xBase, topY+tileH*2,
			xBase-blockWidth, topY+tileH)

		// Left face:
		// P4 -> P3 -> P3+bldgH -> P4+bldgH
		pLeft := fmt.Sprintf("%.1f,%.1f %.1f,%.1f %.1f,%.1f %.1f,%.1f",
			xBase-blockWidth, topY+tileH,
			xBase, topY+tileH*2,
			xBase, yBase+tileH*2,
			xBase-blockWidth, yBase+tileH)

		// Right face:
		// P3 -> P2 -> P2+bldgH -> P3+bldgH
		pRight := fmt.Sprintf("%.1f,%.1f %.1f,%.1f %.1f,%.1f %.1f,%.1f",
			xBase, topY+tileH*2,
			xBase+blockWidth, topY+tileH,
			xBase+blockWidth, yBase+tileH,
			xBase, yBase+tileH*2)

		// Activity color intensity based on weekly total
		activityLevel := 0
		if b.WeeklyTotal > 0 {
			activityLevel = 1 + int((float64(b.WeeklyTotal)/float64(scene.MaxWeeklyTotal+1))*3)
			if activityLevel > 4 {
				activityLevel = 4
			}
		}
		winColor := theme.WindowLevels[activityLevel]

		tooltip := fmt.Sprintf("Week %d (%s)&#10;Total: %d contributions&#10;Floors: %d&#10;District: %s",
			b.WeekIndex+1, b.FirstDay, b.WeeklyTotal, b.Floors, b.District)

		buf.WriteString(fmt.Sprintf(`<g class="iso-building"><title>%s</title>`, tooltip))

		// Draw Left Face
		buf.WriteString(fmt.Sprintf(`<polygon points="%s" fill="%s" stroke="%s" stroke-width="0.5" />`,
			pLeft, theme.BuildingSide3D, theme.BuildingEdge))

		// Draw Right Face (highlight side)
		buf.WriteString(fmt.Sprintf(`<polygon points="%s" fill="%s" stroke="%s" stroke-width="0.5" />`,
			pRight, theme.BuildingFront3D, theme.BuildingEdge))

		// Draw Top Roof Face
		roofColor := theme.BuildingTop3D
		if b.HasAntenna {
			roofColor = theme.BuildingRoof
		}
		buf.WriteString(fmt.Sprintf(`<polygon points="%s" fill="%s" stroke="%s" stroke-width="0.5" />`,
			pTop, roofColor, theme.BuildingEdge))

		// Draw Windows / Activity bands on facades
		for f := 1; f < b.Floors; f++ {
			floorOffsetY := float64(f) * heightScale
			winY := yBase - floorOffsetY + tileH

			// Left window strip
			buf.WriteString(fmt.Sprintf(`<polygon points="%.1f,%.1f %.1f,%.1f %.1f,%.1f %.1f,%.1f" fill="%s" opacity="0.85" />`,
				xBase-blockWidth+3, winY+2,
				xBase-2, winY+tileH+1,
				xBase-2, winY+tileH+4,
				xBase-blockWidth+3, winY+5,
				winColor))

			// Right window strip
			buf.WriteString(fmt.Sprintf(`<polygon points="%.1f,%.1f %.1f,%.1f %.1f,%.1f %.1f,%.1f" fill="%s" opacity="0.95" />`,
				xBase+2, winY+tileH+1,
				xBase+blockWidth-3, winY+2,
				xBase+blockWidth-3, winY+5,
				xBase+2, winY+tileH+4,
				winColor))
		}

		// Antenna on tallest / busiest skyscraper
		if b.HasAntenna {
			buf.WriteString(fmt.Sprintf(`<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" class="antenna" />`,
				xBase, topY+tileH, xBase, topY-20))
			buf.WriteString(fmt.Sprintf(`<circle cx="%.1f" cy="%.1f" r="4" class="beacon" />`,
				xBase, topY-20))
		}

		buf.WriteString(`</g>`)
	}

	// Month Timeline Labels
	monthY := baseY + 45.0
	for _, ml := range scene.MonthLabels {
		xPos := startX + float64(ml.Column)*tileW*0.8
		if xPos < svgWidth-80 {
			buf.WriteString(fmt.Sprintf(`<text x="%.1f" y="%.1f" class="subtitle" font-weight="bold">%s</text>`,
				xPos, monthY, ml.MonthName))
		}
	}

	// Footer Info
	buf.WriteString(fmt.Sprintf(`<text x="40" y="%.1f" class="stat-label">GitHub Contribution City • 3D Isometric View • Built with Go</text>`,
		svgHeight-15))

	buf.WriteString("\n</svg>")
	return buf.String()
}
